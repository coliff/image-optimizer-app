<#
.SYNOPSIS
  Packs a published build into an MSIX package for the Microsoft Store (ImageOptimizer-<version>-x64.msix).
.DESCRIPTION
  Builds the File Explorer menu DLL (src/ImageOptimizer.ShellMenu), lays out the published app with
  src/ImageOptimizer.Package's manifest and images, and packs it with the Windows SDK's makeappx.
  The package is unsigned: the Store signs it when it's submitted in Partner Center.
  To try it on your own PC, turn on Developer Mode in Windows Settings and run it with -Register, which
  installs the unpacked layout in place of the Store version.
  Needs the Windows SDK, CMake and Visual Studio's C++ tools (all on GitHub's windows-latest runners).
#>
param(
  [Parameter(Mandatory)] [string]$Version,
  [string]$PublishDir = 'publish',
  [string]$OutputDir = 'msix',
  [switch]$Register
)

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$work = Join-Path $root 'artifacts/msix'
$layout = Join-Path $work 'layout'

if ($Version -notmatch '^\d+\.\d+\.\d+$') { throw "'$Version' isn't a version like 1.2.3" }
if (-not (Test-Path (Join-Path $PublishDir 'ImageOptimizer.exe'))) { throw "ImageOptimizer.exe isn't in '$PublishDir'. Run dotnet publish first." }

function Find-SdkTool([string]$name) {
  $tool = Get-ChildItem "${env:ProgramFiles(x86)}\Windows Kits\10\bin\10.*\x64\$name" -ErrorAction SilentlyContinue |
    Sort-Object { [version]$_.Directory.Parent.Name } | Select-Object -Last 1
  if (-not $tool) { throw "$name wasn't found. Install the Windows SDK." }
  $tool.FullName
}

function Invoke-Tool([string]$Tool, [string[]]$Arguments) {
  & $Tool @Arguments
  if ($LASTEXITCODE -ne 0) { throw "$(Split-Path $Tool -Leaf) failed with exit code $LASTEXITCODE" }
}

Remove-Item $work -Recurse -Force -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Path $work, $layout | Out-Null

# The menu's text comes from ExplorerMenuLabel in the app's Strings*.resx, so it's translated like the rest.
$labels = foreach ($resx in Get-ChildItem (Join-Path $root 'src/ImageOptimizer.App') -Filter 'Strings*.resx') {
  $language = if ($resx.BaseName -match '^Strings\.(.+)$') { $Matches[1] } else { '' }
  $text = ([xml](Get-Content $resx.FullName -Raw -Encoding utf8)).root.data |
    Where-Object name -EQ 'ExplorerMenuLabel' | ForEach-Object { $_.value }
  if (-not $text) { throw "ExplorerMenuLabel is missing from $($resx.Name)" }
  $escaped = $text.Replace('\', '\\').Replace('"', '\"')
  "  {L`"$language`", L`"$escaped`"},"
}
$header = @(
  '// Generated by scripts/pack-msix.ps1 from ExplorerMenuLabel in src/ImageOptimizer.App/Strings*.resx.'
  '#pragma once'
  'struct MenuLabel { const wchar_t* Language; const wchar_t* Text; };'
  'inline constexpr MenuLabel MenuLabels[] = {'
  $labels
  '};'
) -join "`n"
$labelsDir = Join-Path $work 'labels'
New-Item -ItemType Directory -Path $labelsDir | Out-Null
[IO.File]::WriteAllText((Join-Path $labelsDir 'Labels.g.h'), "$header`n", [Text.UTF8Encoding]::new($false))

$shellMenuBuild = Join-Path $work 'shellmenu'
Invoke-Tool -Tool cmake -Arguments '-S', (Join-Path $root 'src/ImageOptimizer.ShellMenu'), '-B', $shellMenuBuild, '-A', 'x64', "-DLABELS_DIR=$labelsDir"
Invoke-Tool -Tool cmake -Arguments '--build', $shellMenuBuild, '--config', 'Release'

# The package's files: the published app, the menu DLL, the images and the manifest with this version.
Copy-Item (Join-Path $PublishDir '*') $layout -Recurse
Copy-Item (Join-Path $shellMenuBuild 'Release/ImageOptimizer.ShellMenu.dll') $layout
$images = Join-Path $root 'src/ImageOptimizer.Package/Images'
Copy-Item $images (Join-Path $layout 'Images') -Recurse

[xml]$manifest = Get-Content (Join-Path $root 'src/ImageOptimizer.Package/Package.appxmanifest') -Raw -Encoding utf8
# The Store needs four parts, with the last one 0.
$manifest.Package.Identity.Version = "$Version.0"
$manifest.Save((Join-Path $layout 'AppxManifest.xml'))

# resources.pri tells Windows which image to use at each size and scale. Only the images are indexed,
# so the app's own files (such as the de\ and ja\ translation folders) are left alone.
$makepri = Find-SdkTool 'makepri.exe'
$priRoot = Join-Path $work 'pri'
New-Item -ItemType Directory -Path $priRoot | Out-Null
Copy-Item $images (Join-Path $priRoot 'Images') -Recurse
Copy-Item (Join-Path $layout 'AppxManifest.xml') $priRoot
$priConfig = Join-Path $work 'priconfig.xml'
Invoke-Tool -Tool $makepri -Arguments 'createconfig', '/cf', $priConfig, '/dq', 'en-US', '/pv', '10.0.0', '/o'
Invoke-Tool -Tool $makepri -Arguments 'new', '/pr', $priRoot, '/cf', $priConfig, '/mn', (Join-Path $priRoot 'AppxManifest.xml'),
  '/of', (Join-Path $layout 'resources.pri'), '/o'

if ($Register) {
  Get-AppxPackage -Name $manifest.Package.Identity.Name | Remove-AppxPackage
  Add-AppxPackage -Register (Join-Path $layout 'AppxManifest.xml')
  "Installed the layout from $layout. Remove it from Windows Settings > Apps when you're done."
}

$makeappx = Find-SdkTool 'makeappx.exe'
New-Item -ItemType Directory -Path $OutputDir -Force | Out-Null
$package = Join-Path (Resolve-Path $OutputDir) "ImageOptimizer-$Version-x64.msix"
Invoke-Tool -Tool $makeappx -Arguments 'pack', '/d', $layout, '/p', $package, '/o'
"Packed $package ({0:N1} MB)" -f ((Get-Item $package).Length / 1MB)
